 public class latihan2 {
    
    public static void main(String[] args) {
        
        // non primitif
        String nama = "rahman";
        // primitif
        int umur = 19;
        char jenisKelamin = 'L';
        double tinggiBadan = 160.5;
        float beratBadan = 45.5f;
        
        // menampilkan hasil 
        System.out.println("Nama \t\t: " + nama);
        System.out.println("Umur \t\t: " + umur);
        System.out.println("Jenis Kelamin \t: " + jenisKelamin);
        System.out.println("Tinggi Badan \t: " + tinggiBadan +"cm");           
        System.out.println("Berat Badan \t: " + beratBadan +"Kg");
        
        
        
        
        
        
        
    }
    
}
